#!/bin/bash
# ==============================================================================
# Webket-Monster 통합 빌드 스크립트
# ==============================================================================
# 이 스크립트는 백엔드(Gradle/SpringBoot)와 프론트엔드(Plasmo/React)를 한 번에 빌드하고,
# 프론트엔드 크롬 익스텐션 패키징(.zip)까지 자동으로 처리합니다.

# 에러 발생 시 즉시 중단
set -e

# 색상 정의
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo -e "${BLUE}================================================================${NC}"
echo -e "${BLUE}🚀  Webket-Monster 백엔드 & 프론트엔드 통합 빌드를 시작합니다...${NC}"
echo -e "${BLUE}================================================================${NC}"

# 스크립트 실행 위치를 기준 경로로 설정
ROOT_DIR="$(cd "$(dirname "$0")" && pwd)"

# ------------------------------------------------------------------------------
# 1. 백엔드 빌드
# ------------------------------------------------------------------------------
echo -e "\n${YELLOW}☕ [1/2] 백엔드 Spring Boot 애플리케이션 빌드 중...${NC}"
cd "${ROOT_DIR}/backend"

# gradlew 실행 권한 부여
if [ ! -x "./gradlew" ]; then
  echo -e "🔧 ./gradlew 파일에 실행 권한을 부여합니다."
  chmod +x ./gradlew
fi

# gradle 빌드 수행 (테스트 제외)
./gradlew clean build -x test

echo -e "${GREEN}✅ 백엔드 빌드 완료!${NC}"
echo -e "📦 JAR 경로: ${ROOT_DIR}/backend/build/libs/backend-0.0.1-SNAPSHOT.jar"


# ------------------------------------------------------------------------------
# 2. 프론트엔드 빌드
# ------------------------------------------------------------------------------
echo -e "\n${YELLOW}📦 [2/2] 프론트엔드 Plasmo 크롬 익스텐션 빌드 및 패키징 중...${NC}"
cd "${ROOT_DIR}/frontend"

# node_modules 확인 및 설치
if [ ! -d "node_modules" ]; then
  echo -e "📦 의존성 패키지가 존재하지 않아 설치를 진행합니다 (npm install)..."
  npm install
fi

# Plasmo Chrome Extension 빌드 및 zip 패키징 수행
npm run build:zip

echo -e "${GREEN}✅ 프론트엔드 빌드 및 패키징 완료!${NC}"
echo -e "📦 ZIP 파일 경로: ${ROOT_DIR}/frontend/build/chrome-mv3-prod.zip"


# ------------------------------------------------------------------------------
# 3. 완료 안내
# ------------------------------------------------------------------------------
echo -e "\n${BLUE}================================================================${NC}"
echo -e "${GREEN}🎉 모든 빌드와 패키징이 성공적으로 끝났습니다!${NC}"
echo -e "${BLUE}================================================================${NC}"
echo -e "1. 백엔드 로컬 실행 방법:"
echo -e "   - $ cd backend && ./gradlew bootRun"
echo -e "   - $ cd backend && docker-compose up --build -d (Docker 환경)"
echo -e "2. 프론트엔드 크롬 익스텐션 패키지:"
echo -e "   - ${ROOT_DIR}/frontend/build/chrome-mv3-prod.zip 파일을 압축 해제 후"
echo -e "     chrome://extensions 에서 '압축해제된 확장 프로그램을 로드'하여 설치하실 수 있습니다."
echo -e "${BLUE}================================================================${NC}"
